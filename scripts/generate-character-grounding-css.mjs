import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const profilePath = resolve(root, "src/meta/characterGroundingProfiles.json");
const outputPath = resolve(root, "src/meta/CharacterGrounding.generated.css");
const data = JSON.parse(readFileSync(profilePath, "utf8"));

function pct(value, sourceFrameSize) {
  return `${(value / sourceFrameSize * 100).toFixed(4)}%`;
}

function contactVars(contact, defaults, prefix, sourceFrameSize) {
  const opacity = contact.opacity ?? defaults.opacity;
  return [
    `  --nd-${prefix}-x: ${pct(contact.x, sourceFrameSize)};`,
    `  --nd-${prefix}-y: ${pct(contact.y, sourceFrameSize)};`,
    `  --nd-${prefix}-rx: ${pct(contact.radiusX ?? defaults.radiusX, sourceFrameSize)};`,
    `  --nd-${prefix}-ry: ${pct(contact.radiusY ?? defaults.radiusY, sourceFrameSize)};`,
    `  --nd-${prefix}-opacity: ${opacity.toFixed(3)};`,
    `  --nd-${prefix}-mid-opacity: ${(opacity * 0.5).toFixed(3)};`,
  ];
}

const lines = [
  "/* AUTO-GENERATED by scripts/generate-character-grounding-css.mjs. */",
  "/* Edit src/meta/characterGroundingProfiles.json, never this file directly. */",
  "",
];

for (const [bodyId, profile] of Object.entries(data.profiles)) {
  const source = profile.sourceFrameSize;
  const defaults = profile.contactDefaults;
  if (!Array.isArray(profile.directions) || profile.directions.length !== 8) {
    throw new Error(`${bodyId}: expected exactly 8 directional grounding entries.`);
  }

  profile.directions.forEach((direction, index) => {
    if (!Array.isArray(direction.contacts) || direction.contacts.length < 1 || direction.contacts.length > 2) {
      throw new Error(`${bodyId}/${direction.name}: expected 1 or 2 contacts.`);
    }
    const selector = `.zk-player:has(.zk-directional-sprite[style*="${profile.assetNeedle}"]).dir-${index}`;
    const meanContactY = direction.contacts.reduce((sum, contact) => sum + contact.y, 0) / direction.contacts.length;
    const ambientY = meanContactY + profile.ambient.offsetYFromContactMean;
    lines.push(`${selector} {`);
    lines.push(`  --nd-ground-foot-y: ${pct(direction.footY, source)};`);
    lines.push(`  --nd-ground-ambient-x: 50%;`);
    lines.push(`  --nd-ground-ambient-y: ${pct(ambientY, source)};`);
    lines.push(`  --nd-ground-ambient-w: ${pct(profile.ambient.width, source)};`);
    lines.push(`  --nd-ground-ambient-h: ${pct(profile.ambient.height, source)};`);
    lines.push(`  --nd-ground-ambient-core-opacity: ${profile.ambient.coreOpacity.toFixed(3)};`);
    lines.push(`  --nd-ground-ambient-mid-opacity: ${profile.ambient.midOpacity.toFixed(3)};`);
    lines.push(...contactVars(direction.contacts[0], defaults, "ground-contact-a", source));
    if (direction.contacts[1]) {
      lines.push(...contactVars(direction.contacts[1], defaults, "ground-contact-b", source));
    } else {
      lines.push(`  --nd-ground-contact-b-opacity: 0;`);
      lines.push(`  --nd-ground-contact-b-mid-opacity: 0;`);
    }
    lines.push("}", "");
  });
}

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, `${lines.join("\n")}\n`);
console.log(`Character grounding CSS: generated ${outputPath}`);
