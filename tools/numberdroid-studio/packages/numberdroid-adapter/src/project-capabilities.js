import {
  ASSET_KINDS,
  MAX_ASSET_PROPOSAL_ITEMS,
  MAX_ATLAS_OUTPUT_BYTES,
  MAX_ATLAS_OUTPUT_PIXELS,
  MAX_ATLAS_RECTANGLES,
  MAX_ROOM_AXIS_CELLS,
  MAX_ROOM_CELLS,
  MAX_ROOM_CONNECTORS,
  MAX_ROOM_PLACEMENTS,
  projectCapabilityManifestSha256,
  validateProjectCapabilityManifest,
} from '../../domain/src/index.js';

const formats = Object.freeze({
  projectDocument: 'studio.project-document',
  adapterBindings: 'studio.adapter-bindings',
  artifactVerification: 'studio.artifact-verification-closure',
  exportProfile: 'studio.export-profile',
  exportSnapshot: 'numberdroid.export-snapshot',
  levelSpec: 'numberdroid.level-spec',
  compiledLevelSpec: 'numberdroid.compiled-level-spec',
  workbenchPlan: 'numberdroid.workbench-plan',
  studioRoom: 'numberdroid.studio-room',
  provenance: 'numberdroid.provenance',
  copyDescriptor: 'studio.cas-copy-descriptor',
  candidate: 'numberdroid.export-candidate',
  candidateManifest: 'numberdroid.export-candidate-manifest',
});

export function createNumberdroidProjectCapabilityProfile(adapterVersion) {
  const manifest = validateProjectCapabilityManifest({
    schemaVersion: 1,
    kind: 'studio.project-capability-manifest',
    profileId: 'numberdroid.studio',
    profileVersion: 1,
    adapter: {
      id: 'numberdroid',
      version: adapterVersion,
    },
    assetKinds: ASSET_KINDS,
    coordinateModel: {
      dimensions: 2,
      origin: 'top-left',
      axes: { x: 'right', y: 'down' },
      units: [
        { id: 'tile', integer: true, pixelsPerUnit: 64 },
        { id: 'pixel', integer: true, pixelsPerUnit: 1 },
      ],
      defaultUnitId: 'tile',
      rotation: {
        unit: 'degrees',
        positiveDirection: 'clockwise',
        values: [0, 90, 180, 270],
      },
    },
    modules: [
      { id: 'studio.asset', version: 'v2' },
      { id: 'studio.room-grid', version: 'v1' },
      { id: 'studio.export-snapshot', version: 'v1' },
      { id: 'studio.candidate-build', version: 'v1' },
      { id: 'numberdroid.level-spec', version: 'v0' },
    ],
    vocabulary: {
      spaceKinds: ['room', 'corridor'],
      relationKinds: [
        'adjacent',
        'north_of',
        'south_of',
        'east_of',
        'west_of',
        'north_east_of',
        'north_west_of',
        'south_east_of',
        'south_west_of',
      ],
      connectionKinds: ['opening', 'standard-door', 'controlled-door'],
      propRoles: ['hero', 'support', 'furniture', 'dressing'],
      actorKinds: ['encounter', 'staged'],
      routeKinds: ['patrol', 'passby', 'scripted'],
      pickupKinds: ['access-key'],
      zoneAnchorKinds: ['space-center', 'connection', 'prop', 'actor', 'route', 'pickup'],
      triggerKinds: [
        'enter-space',
        'enter-zone',
        'interact',
        'collect',
        'state-change',
        'proximity',
        'timer',
      ],
      conditionKinds: [],
      actionKinds: [
        'set-flag',
        'grant-key',
        'unlock-door',
        'lock-door',
        'spawn-actor',
        'despawn-actor',
        'move-actor',
        'actor-passby',
        'story-beat',
      ],
      variableTypes: [],
    },
    operations: [
      {
        id: 'numberdroid.adapter.snapshot-room-candidate',
        kind: 'snapshot',
        version: 1,
        moduleIds: ['studio.asset', 'studio.room-grid', 'studio.export-snapshot'],
        inputFormatIds: [
          formats.projectDocument,
          formats.adapterBindings,
          formats.artifactVerification,
          formats.exportProfile,
        ],
        outputFormatIds: [formats.exportSnapshot],
      },
      {
        id: 'numberdroid.compiler.validate-placement-overrides',
        kind: 'validate',
        version: 1,
        moduleIds: ['numberdroid.level-spec'],
        inputFormatIds: [formats.levelSpec],
        outputFormatIds: [],
      },
      {
        id: 'numberdroid.compiler.compile-level-spec',
        kind: 'compile',
        version: 1,
        moduleIds: ['numberdroid.level-spec'],
        inputFormatIds: [formats.levelSpec],
        outputFormatIds: [formats.compiledLevelSpec],
      },
      {
        id: 'numberdroid.compiler.compile-workbench-plan',
        kind: 'compile',
        version: 1,
        moduleIds: ['numberdroid.level-spec'],
        inputFormatIds: [formats.levelSpec],
        outputFormatIds: [formats.workbenchPlan],
      },
      {
        id: 'numberdroid.adapter.build-room-candidate',
        kind: 'candidate',
        version: 1,
        moduleIds: ['studio.candidate-build', 'studio.export-snapshot', 'numberdroid.level-spec'],
        inputFormatIds: [formats.exportSnapshot],
        outputFormatIds: [
          formats.levelSpec,
          formats.studioRoom,
          formats.provenance,
          formats.copyDescriptor,
          formats.candidate,
          formats.candidateManifest,
        ],
      },
    ],
    outputFormats: [
      { id: formats.projectDocument, version: 3, mediaType: 'application/json' },
      { id: formats.adapterBindings, version: 1, mediaType: 'application/json' },
      { id: formats.artifactVerification, version: 1, mediaType: 'application/json' },
      { id: formats.exportProfile, version: 1, mediaType: 'application/json' },
      { id: formats.exportSnapshot, version: 1, mediaType: 'application/json' },
      { id: formats.levelSpec, version: 0, mediaType: 'application/json' },
      { id: formats.compiledLevelSpec, version: 0, mediaType: 'application/json' },
      { id: formats.workbenchPlan, version: 1, mediaType: 'application/json' },
      { id: formats.studioRoom, version: 1, mediaType: 'application/json' },
      { id: formats.provenance, version: 1, mediaType: 'application/json' },
      { id: formats.copyDescriptor, version: 1, mediaType: 'application/json' },
      { id: formats.candidate, version: 1, mediaType: 'application/json' },
      { id: formats.candidateManifest, version: 1, mediaType: 'application/json' },
    ],
    limits: [
      { id: 'studio.atlas.max-rectangles', value: MAX_ATLAS_RECTANGLES, unit: 'items' },
      { id: 'studio.atlas.max-output-pixels', value: MAX_ATLAS_OUTPUT_PIXELS, unit: 'pixels' },
      { id: 'studio.atlas.max-output-bytes', value: MAX_ATLAS_OUTPUT_BYTES, unit: 'bytes' },
      { id: 'studio.asset.max-proposal-items', value: MAX_ASSET_PROPOSAL_ITEMS, unit: 'items' },
      { id: 'studio.room.max-axis-cells', value: MAX_ROOM_AXIS_CELLS, unit: 'cells' },
      { id: 'studio.room.max-cells', value: MAX_ROOM_CELLS, unit: 'cells' },
      { id: 'studio.room.max-connectors', value: MAX_ROOM_CONNECTORS, unit: 'items' },
      { id: 'studio.room.max-placements', value: MAX_ROOM_PLACEMENTS, unit: 'items' },
    ],
    extensions: {
      'numberdroid.studio': {
        levelSpecContract: 'v0',
        exportScope: 'final-room-or-hallway',
        candidateOnly: true,
        unsupportedFeatures: [
          'actor-authoring',
          'actor-defeated-trigger',
          'drop-actions',
          'visible-text',
          'typed-variables',
          'typed-conditions',
          'waves',
          'spawners',
          'item-export',
          'floor-runtime-mapping',
          'materialize',
          'commit',
          'publish',
        ],
      },
    },
  });
  return Object.freeze({
    manifest,
    fingerprint: projectCapabilityManifestSha256(manifest),
  });
}
